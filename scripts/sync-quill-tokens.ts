/**
 * Copies PostHog's Quill design tokens into styles/quill-tokens.css.
 *
 *   pnpm sync:quill [path to posthog/packages/quill/packages/tokens/dist]
 *
 * Quill switches to dark mode with a `.dark` class, which needs JavaScript, and HostHog's
 * sandbox blocks scripts on this site. So the dark blocks are rewritten to follow the
 * system setting with `prefers-color-scheme` instead. The theme tokens Quill keeps in
 * Tailwind's `@theme` (fonts, type sizes, radius, shadows) become plain `:root` variables.
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const distDir = path.resolve(process.argv[2] ?? "../posthog/packages/quill/packages/tokens/dist");
const colorSystem = readFileSync(path.join(distDir, "color-system.css"), "utf8");
const tailwind = readFileSync(path.join(distDir, "tailwind.css"), "utf8");

const DARK = ':is(.dark, [theme="dark"], [data-theme="dark"])';
const DARK_DESCENDANTS = `:is(${DARK}, ${DARK} *)`;

/** Rewrites a `selector { … }` block into `@media (prefers-color-scheme: dark) { replacement { … } }`. */
function toMediaQuery(css: string, selector: string, replacement: string): string {
  let out = css;
  for (;;) {
    const start = out.indexOf(`${selector} {`);
    if (start === -1) return out;
    const end = out.indexOf("\n}", start);
    const body = out.slice(start + selector.length + 2, end);
    out = `${out.slice(0, start)}@media (prefers-color-scheme: dark) {\n  ${replacement} {${body.replace(/\n/g, "\n  ")}\n  }\n}${out.slice(end + 2)}`;
  }
}

// The descendant selector contains the plain one, so it goes first.
let colors = toMediaQuery(colorSystem, DARK_DESCENDANTS, "*");
colors = toMediaQuery(colors, DARK, ":root");
if (colors.includes(".dark"))
  throw new Error("A dark-mode selector was left over; check Quill's output format");

const themeVars = [
  ...new Set(
    tailwind
      .split("\n")
      .map((line) => line.trim())
      .filter((line) => /^--(font|text|radius|shadow|spacing)[\w-]*:/.test(line)),
  ),
];
if (themeVars.length < 10)
  throw new Error("Found too few theme tokens; check Quill's tailwind.css");

let source = "unknown";
try {
  source = execFileSync("git", ["log", "-1", "--format=%h %cs", "--", "."], {
    cwd: path.resolve(distDir, ".."),
    encoding: "utf8",
  }).trim();
} catch {
  // Not a git checkout: keep "unknown".
}

const out = `/*
 * PostHog Quill design tokens (MIT, PostHog Inc.). Generated by scripts/sync-quill-tokens.ts, do not edit.
 * Source: posthog/packages/quill/packages/tokens/dist, last changed in ${source}.
 * Dark mode follows the system setting instead of Quill's .dark class.
 */

${colors.replace(/^\/\*.*Auto-generated.*\*\/\n/m, "").trim()}

/* Theme tokens from Quill's @theme block */
:root {
  --text-ui: 0.8125rem;
${themeVars.map((line) => `  ${line}`).join("\n")}
}
`;

writeFileSync(path.resolve("styles/quill-tokens.css"), out);
console.log(
  `Wrote styles/quill-tokens.css from ${distDir} (${source}), ${themeVars.length} theme tokens.`,
);
